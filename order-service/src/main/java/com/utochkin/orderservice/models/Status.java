package com.utochkin.orderservice.models;

public enum Status {
    /** Заказ создан, но остатки товаров ещё не списаны в shop-service (транзитная стадия «до списания»). */
    STOCK_PENDING,
    /** Остатки списаны, заказ ожидает оплаты покупателем. */
    WAITING_FOR_PAYMENT,
    /** CAS-захват перед оплатой/возвратом: заказ временно «занят» одним потоком (застрявшие случаи разбирает ReconciliationJob). */
    PROCESSING,
    /** Заказ оплачен; до перевода в DELIVERING действует 5-минутное окно возврата. */
    SUCCESS,
    /** Товар недоступен или платёж не прошёл — заказ закрыт без доставки. */
    FAILED,
    /** Возврат выполнен: деньги возвращены на карту, остатки товаров восстановлены в shop-service. */
    REFUNDED,
    /** Заказ передан в доставку (T+5 минут после оплаты) — возврат уже невозможен. */
    DELIVERING,
    /** Заказ вручён покупателю — финальный статус, возврат невозможен. */
    DELIVERED
}
